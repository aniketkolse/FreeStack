/**
 * Deterministic fallback popularity score (higher = more popular) for large
 * unbounded categories (MCP 4,600+, APIs 2,200+) beyond their curated head.
 */
export function computeUnrankedPopularityScore(offer: Offer): number {
  let score = 0;

  if (offer.metadata.featured) score += 1000;
  if (offer.classification.tags.includes('official-implementation')) score += 800;

  const provider = offer.identity.provider || '';
  const slugAndName = `${offer.identity.slug} ${offer.identity.name} ${provider}`;

  if (MAJOR_ECOSYSTEM_PROVIDERS.test(provider)) {
    score += 500;
  } else if (HIGH_DEMAND_MCP_OR_API_PATTERNS.test(slugAndName)) {
    score += 240;
  }

  if (offer.classification.tags.includes('glama-verified')) score += 160;
  if (offer.classification.tags.includes('cors-enabled')) score += 70;
  if (offer.classification.tags.includes('no-api-key')) score += 50;

  if (HIGH_UTILITY_SUBCATEGORIES.has(offer.classification.subcategory)) {
    score += 60;
  }

  if (offer.access.requirements.card_required === 'not_required') score += 40;
  if (offer.access.requirements.account_required === 'not_required') score += 25;
  if (offer.verification.status === 'verified') score += 20;
  if (offer.identity.logo_url) score += 15;

  // Penalize numbered duplicate variants (e.g. *-api-2) so primaries rank cleanly above clones
  if (/-\d+$/.test(offer.identity.slug)) score -= 300;

  return score;
}

const TAIL_BASE_RANK = 10_000;
const MAX_HEURISTIC_SCORE = 5_000;

/**
 * Computes a single strictly ordered scalar key per offer for O(N log N) sorting:
 * - Same category: matches curated #1..#N exactly, followed by descending heuristic score.
 * - Cross category (/explore): interleaves Rank #1 across all 11 stacks, then Rank #2, etc.
 */
export function getPopularitySortKey(offer: Offer): number {
  const cat = offer.classification.category;
  const catMap = RANK_MAP_BY_CATEGORY.get(cat);
  const pinnedRank = catMap?.get(offer.identity.slug);

  const withinCategoryRank =
    pinnedRank !== undefined
      ? pinnedRank
      : TAIL_BASE_RANK + (MAX_HEURISTIC_SCORE - computeUnrankedPopularityScore(offer));

  const catOffset = CATEGORY_GLOBAL_OFFSET[cat] ?? 11;
  return withinCategoryRank * 16 + catOffset;
}

export function getPinnedCategoryRank(category: CategorySlug, slug: string): number | undefined {
  return RANK_MAP_BY_CATEGORY.get(category)?.get(slug);
}

export function compareOffersByPopularity(a: Offer, b: Offer): number {
  const keyA = getPopularitySortKey(a);
  const keyB = getPopularitySortKey(b);
  if (keyA !== keyB) return keyA - keyB;

  const da = a.verification.last_verified_at ?? '';
  const db = b.verification.last_verified_at ?? '';
  if (db !== da) return db.localeCompare(da);

  return a.identity.name.localeCompare(b.identity.name);
}

/**
 * Resolves a local official company or specific AI model logo if matched.
 * Also matches 3rd-party MCP servers and APIs that reference a company name in their title, slug, provider, URL, or description.
 */
export function resolveOfferBrandLogoSrc(
  offer: Pick<Offer, 'identity'> & Partial<Pick<Offer, 'classification' | 'links' | 'description'>>
): string | null {
  const mapped = SLUG_TO_LOGO_PATH[offer.identity.slug];
  if (mapped) return mapped;

  const primaryText = `${offer.identity.name} ${offer.identity.provider} ${offer.identity.slug}`;
  for (const [pattern, logoPath] of PROVIDER_FALLBACKS) {
    if (pattern.test(primaryText)) {
      return logoPath;
    }
  }

  const officialUrl = offer.links?.official || offer.links?.documentation || '';
  let nonGithubHost = '';
  if (officialUrl) {
    try {
      const host = new URL(officialUrl).hostname.toLowerCase();
      if (!host.includes('github.com') && !host.endsWith('.github.io')) {
        nonGithubHost = host;
      }
    } catch {
      // ignore invalid URL
    }
  }

  if (nonGithubHost) {
    for (const [pattern, logoPath] of PROVIDER_FALLBACKS) {
      if (pattern.test(nonGithubHost)) {
        return logoPath;
      }
    }
  }

  const cleanedDesc = (offer.description || '')
    .replace(/(?:Official|Verified)?\s*[^.]*MCP server\s*\([^)]*\)\.?/gi, '')
    .replace(/\bgit-history\b/gi, '');

  if (cleanedDesc.trim()) {
    for (const [pattern, logoPath] of PROVIDER_FALLBACKS) {
      if (DESCRIPTION_SKIP_PATTERNS.has(logoPath)) continue;
      if (pattern.test(cleanedDesc)) {
        return logoPath;
      }
    }
  }

  return offer.identity.logo_url ?? null;
}

/**
 * For independent websites or GitHub repositories not in the local SVG brand registry,
 * resolves the official GitHub organization/author avatar or official website favicon.
 */
export function resolveOfferRemoteBrandUrl(
  offer: Pick<Offer, 'identity'> & Partial<Pick<Offer, 'links'>>
): string | null {
  const rawUrl = offer.links?.official || offer.links?.documentation;
  if (!rawUrl) return null;

  try {
    const parsed = new URL(rawUrl);
    const host = parsed.hostname.toLowerCase();

    if (host === 'github.com' || host === 'www.github.com') {
      const segments = parsed.pathname.split('/').filter(Boolean);
      if (segments.length >= 1 && segments[0]) {
        return `https://github.com/${encodeURIComponent(segments[0])}.png?size=128`;
      }
    }

    if (host.endsWith('.github.io')) {
      const owner = host.replace(/\.github\.io$/, '');
      if (owner && !owner.includes('.')) {
        return `https://github.com/${encodeURIComponent(owner)}.png?size=128`;
      }
    }

    if (host && host !== 'localhost') {
      const normalizedDomain = host.replace(
        /^(?:api|docs|mcp|developers?|dev|userguide|portal|reference|v[1234])\.(?=[^.]+\.[^.]+$)/,
        ''
      );
      return `https://www.google.com/s2/favicons?domain=${encodeURIComponent(normalizedDomain)}&sz=128`;
    }
  } catch {
    return null;
  }

  return null;
}

/**
 * Resolves a local logo path in /logos/* guaranteed to exist on disk.
 */
export function resolveOfferLogoSrc(
  offer: Pick<Offer, 'identity'> & Partial<Pick<Offer, 'classification' | 'links' | 'description'>>
): string | null {
  const brandLogo = resolveOfferBrandLogoSrc(offer);
  if (brandLogo) return brandLogo;

  const subcat = offer.classification?.subcategory;
  if (offer.classification?.category === 'mcp') {
    if (subcat && MCP_SUBCATEGORY_TO_LOGO_PATH[subcat]) {
      return MCP_SUBCATEGORY_TO_LOGO_PATH[subcat];
    }
    return '/logos/mcp.svg';
  }

  if (subcat && API_SUBCATEGORY_TO_LOGO_PATH[subcat]) {
    return API_SUBCATEGORY_TO_LOGO_PATH[subcat];
  }

  if (subcat && MCP_SUBCATEGORY_TO_LOGO_PATH[subcat]) {
    return MCP_SUBCATEGORY_TO_LOGO_PATH[subcat];
  }

  if (offer.classification?.category === 'apis-integrations') {
    return '/logos/api-development.svg';
  }

  return offer.identity.logo_url ?? null;
}
